export function searchKodePos(query = '', format = 'table') {
    const q = (query || '').trim().toLowerCase();
    const list = q
        ? DATA_KODEPOS.filter((item) =>
            item.kodePos.includes(q) ||
            item.kelurahan.toLowerCase().includes(q) ||
            item.kecamatan.toLowerCase().includes(q) ||
            item.kota.toLowerCase().includes(q) ||
            item.provinsi.toLowerCase().includes(q),
        )
        : DATA_KODEPOS;

    if (format === 'json') {
        return JSON.stringify(list, null, 2);
    }

    if (format === 'csv') {
        const rows = ['kode_pos,kelurahan,kecamatan,kota_kabupaten,provinsi'];
        for (const item of list) {
            rows.push(`${item.kodePos},"${item.kelurahan}","${item.kecamatan}","${item.kota}","${item.provinsi}"`);
        }
        return rows.join('\n');
    }

    // Default: formatted table
    const lines = [];
    lines.push(`Ditemukan ${list.length} data wilayah:`);
    lines.push('');
    lines.push('Kode Pos | Kelurahan / Desa      | Kecamatan           | Kota / Kabupaten    | Provinsi');
    lines.push('---------+-----------------------+---------------------+---------------------+-----------------');
    for (const item of list) {
        const kp = item.kodePos.padEnd(8);
        const kel = item.kelurahan.padEnd(21);
        const kec = item.kecamatan.padEnd(19);
        const kota = item.kota.padEnd(19);
        lines.push(`${kp} | ${kel} | ${kec} | ${kota} | ${item.provinsi}`);
    }
    return lines.join('\n');
}
